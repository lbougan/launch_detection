"""Held-out site evaluation: inference -> postprocess -> site metrics; optional README table."""

from __future__ import annotations

import json
import logging
from dataclasses import asdict, dataclass
from pathlib import Path

from libs.features.stats import load_stats
from libs.geo.postprocess import deduplicate_detections, score_detections, threshold_and_extract
from libs.inference.predictors import Predictor
from libs.inference.sliding_window import run_sliding_window
from services.training.metrics import fp_per_1000km2, reliability_bins, site_recall_at_k

logger = logging.getLogger(__name__)
START_MARK, END_MARK = "<!-- EVAL:START -->", "<!-- EVAL:END -->"
STRIP_ROWS = 1024  # rows per read when counting valid pixels


@dataclass(frozen=True)
class EvalResult:
    split: str
    n_sites: int
    scanned_km2: float
    recall_at_5: float
    recall_at_10: float
    recall_at_20: float
    fp_per_1000km2: float
    n_detections: int
    reliability: dict
    checkpoint: str


def scanned_area_km2(composite_paths: list[Path]) -> float:
    """Area of the pixels that hold data (band 1 not NaN), in km²; read in row strips."""
    import numpy as np
    import rasterio
    from rasterio.windows import Window

    total = 0.0
    for p in composite_paths:
        with rasterio.open(p) as src:
            if not src.crs.is_projected:
                raise ValueError(f"{p} is not in a metric CRS")
            valid = 0
            for r0 in range(0, src.height, STRIP_ROWS):
                n = min(STRIP_ROWS, src.height - r0)
                valid += int(
                    np.count_nonzero(~np.isnan(src.read(1, window=Window(0, r0, src.width, n))))
                )
            total += abs(src.transform.a * src.transform.e) * valid / 1e6
    return total


def evaluate_composites(
    predictor: Predictor,
    composite_paths: list[Path],
    stats_path: Path,
    sites: list[dict],
    out_dir: Path,
    split: str,
    checkpoint: str = "",
    threshold: float = 0.5,
) -> EvalResult:
    stats = load_stats(stats_path)
    preds: list[dict] = []
    for comp in composite_paths:
        prob = run_sliding_window(comp, out_dir / f"{Path(comp).stem}_prob.tif", predictor, stats)
        dets = score_detections(threshold_and_extract(prob, threshold=threshold))
        dets = deduplicate_detections(dets)
        preds.extend(
            {
                "centroid_lon": d.centroid_lon,
                "centroid_lat": d.centroid_lat,
                "prob": d.prob,
                "rank_score": d.rank_score,
            }
            for d in dets
        )
    area = scanned_area_km2(composite_paths)
    return EvalResult(
        split=split,
        n_sites=len(sites),
        scanned_km2=area,
        recall_at_5=site_recall_at_k(preds, sites, 5),
        recall_at_10=site_recall_at_k(preds, sites, 10),
        recall_at_20=site_recall_at_k(preds, sites, 20),
        fp_per_1000km2=fp_per_1000km2(preds, sites, area),
        n_detections=len(preds),
        reliability=reliability_bins(preds, sites),
        checkpoint=checkpoint,
    )


def markdown_table(results: list[EvalResult]) -> str:
    head = "| split | sites | scanned km² | recall@5 | recall@10 | recall@20 | FP / 1000 km² | detections |\n|---|---:|---:|---:|---:|---:|---:|---:|\n"
    rows = [
        f"| {r.split} | {r.n_sites} | {r.scanned_km2:.0f} | {r.recall_at_5:.2f} | {r.recall_at_10:.2f} | {r.recall_at_20:.2f} | {r.fp_per_1000km2:.2f} | {r.n_detections} |"
        for r in results
    ]
    return head + "\n".join(rows) + "\n"


def update_readme(readme: Path, table: str, checkpoint: str, commit: str) -> None:
    text = readme.read_text()
    start, end = text.find(START_MARK), text.find(END_MARK)
    if start < 0 or end < 0 or end < start:
        raise ValueError(f"{readme} needs {START_MARK} ... {END_MARK} in that order")
    block = f"\n_Generated by `uv run python -m services.training.evaluate` at commit `{commit}` with checkpoint `{checkpoint}`._\n\n{table}"
    readme.write_text(text[: start + len(START_MARK)] + block + text[end:])


def build_parser():
    import argparse

    from libs.config import default_stats_path

    ap = argparse.ArgumentParser(description="Evaluate a checkpoint on held-out sites")
    ap.add_argument("--checkpoint", required=True)
    ap.add_argument("--manifest", default="data/manifests/chip_manifest.json")
    ap.add_argument("--stats", default=str(default_stats_path()))
    ap.add_argument("--sites", default="data/manifests/known_sites.json")
    ap.add_argument("--splits", default="data/manifests/splits.json")
    ap.add_argument("--composites-dir", default="data/composites")
    ap.add_argument("--out-dir", default="out/eval")
    ap.add_argument("--split", choices=["val", "test"], action="append", default=None)
    ap.add_argument("--update-readme", type=Path)
    return ap


def main() -> None:
    import subprocess

    from libs.geo.chips import load_known_sites
    from libs.inference.predictors import LocalTorchPredictor

    args = build_parser().parse_args()
    logging.basicConfig(level=logging.INFO)

    sites = load_known_sites(Path(args.sites))
    splits = json.loads(Path(args.splits).read_text())
    manifest = json.loads(Path(args.manifest).read_text())
    predictor = LocalTorchPredictor.from_checkpoint(args.checkpoint)
    results = []
    for split in args.split or ["val", "test"]:
        names = set(splits[split])
        split_sites = [s for s in sites if s["name"] in names]
        aois = sorted({c["aoi"] for c in manifest if c.get("split") == split})
        comps = [Path(args.composites_dir) / f"{a}_composite.tif" for a in aois]
        results.append(
            evaluate_composites(
                predictor,
                comps,
                Path(args.stats),
                split_sites,
                Path(args.out_dir) / split,
                split,
                args.checkpoint,
            )
        )
        Path(args.out_dir).mkdir(parents=True, exist_ok=True)
        (Path(args.out_dir) / f"{split}.json").write_text(json.dumps(asdict(results[-1]), indent=2))
    table = markdown_table(results)
    print(table)
    if args.update_readme:
        commit = (
            subprocess.run(
                ["git", "describe", "--always", "--dirty"],
                capture_output=True,
                text=True,
                check=False,
            ).stdout.strip()
            or "unknown"
        )
        update_readme(args.update_readme, table, args.checkpoint, commit)


if __name__ == "__main__":
    main()
